"""Research report generator: citations, budgets, untrusted sources, plan review (offline)."""
import pytest
from langchain_core.messages import HumanMessage
from streamlit.testing.v1 import AppTest

from conftest import ROOT
from fakes import FakeTavily, script
from projects.research_report import graph
from projects.research_report.graph import (MAX_QUESTIONS, MAX_REVISIONS, ReportSession, build_app,
                                            citation_problems, estimate_cost, number_sources)


def plan(*questions):
    script.structured["ResearchPlan"] = {
        "title": "T", "questions": [{"question": q, "query": f"search {q}"} for q in questions]}


def review(score, decision="accept", gaps=()):
    script.structured["ReviewResult"] = {"score": score, "decision": decision, "feedback": "be specific",
                                         "gaps": list(gaps)}


@pytest.fixture(autouse=True)
def _defaults():
    plan("Q1", "Q2", "Q3")
    script.structured["KeyFacts"] = {"facts": [{"claim": "a fact", "source": 1}]}
    review(9)
    script.reply = lambda system, human: "# Report\n## Summary\nClaim [1]. Another [2].\n## Conclusion\nDone [3]."


def run(**kwargs):
    session = ReportSession(graph=build_app())
    steps = list(session.stream(kwargs.pop("topic", "solid-state batteries"), **kwargs))
    return session, steps


def extractor_prompts():
    return [str(p) for p in script.prompts if "You extract evidence" in str(p)]


