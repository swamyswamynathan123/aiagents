def test_happy_path_researches_in_parallel_and_builds_references():
    session, steps = run()
    r = session.result
    assert r["status"] == "done"
    assert [n for n, _ in steps].count("research") == 3
    assert sorted(f["question"] for f in r["findings"]) == ["Q1", "Q2", "Q3"]
    assert len(r["references"]) == 3 and r["revisions"] == 0
    refs = r["report"].split("## References")[1]
    assert all(f"{i}. [" in refs for i in (1, 2, 3))  # references generated by code, not the model


def test_plan_is_capped():
    plan(*[f"Q{i}" for i in range(8)])
    session, _ = run()
    assert len(session.result["findings"]) == MAX_QUESTIONS


def test_low_scores_revise_until_budget_then_finish():
    review(6, "revise")
    session, _ = run()
    r = session.result
    assert r["status"] == "done"
    assert r["revisions"] == MAX_REVISIONS
    assert r["scores"] == [6] * (MAX_REVISIONS + 1)
    writer_prompts = [p for p in script.prompts if "You write clear" in str(p)]
    assert "Reviewer feedback to address" in str(writer_prompts[-1])


def test_research_more_runs_one_capped_follow_up_round():
    review(5, "research_more", gaps=["G1", "G2", "G3"])
    session, _ = run()
    r = session.result
    assert r["research_rounds"] == graph.MAX_RESEARCH_ROUNDS
    assert sorted(f["question"] for f in r["findings"]) == ["G1", "G2", "Q1", "Q2", "Q3"]  # gaps capped at 2
    assert r["status"] == "done"


def test_invalid_citations_block_acceptance():
    script.reply = lambda system, human: "# R\n## Summary\nClaim [7].\n## Conclusion\nx [1]"
    session, _ = run()
    first = session.result["reviews"][0]
    assert first["invalid_citations"] == [7]
    assert "Fix citations" in first["feedback"]
    assert session.result["revisions"] >= 1  # a 9/10 score was not enough


