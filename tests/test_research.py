def test_citation_problems():
    assert citation_problems("A [1]. B [2, 3]. C [9]. D [0].", 3) == [0, 9]
    assert citation_problems("no citations", 0) == []


def test_sources_are_numbered_once_across_findings():
    src = lambda u: {"title": u, "url": u}  # noqa: E731
    findings = [{"question": "a", "facts": [{"claim": "x", "source": src("u1")}, {"claim": "y", "source": src("u2")}]},
                {"question": "b", "facts": [{"claim": "z", "source": src("u1")}]}]
    assert [(r["n"], r["url"]) for r in number_sources(findings)] == [(1, "u1"), (2, "u2")]


def test_estimate_cost():
    usage = {"gpt-4o-mini-2024-07-18": {"input_tokens": 1_000_000, "output_tokens": 1_000_000}}
    assert estimate_cost(usage) == pytest.approx(0.75)
    assert estimate_cost({"unknown-model": {"input_tokens": 10, "output_tokens": 10}}) == 0


